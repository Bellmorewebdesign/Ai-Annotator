"""Render the study summary as Markdown and PDF.

Prose comes from the model; every quotation and page number comes from verified
annotations, so the summary cannot contain fabricated quotes or page references.
Citations to unknown annotation ids are dropped.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from ..engine.annotate import PlacedAnnotation
from ..engine.convert import register_fonts

SECTION_ORDER = ["Supporting evidence", "Major findings", "Methods", "Key terms", "Counterarguments", "Limitations"]


@dataclass
class SummaryDoc:
    document_name: str
    title: str
    purpose: str
    sections: list[tuple[str, list[tuple[str, list[PlacedAnnotation]]]]]
    rubric: list[tuple[str, str, list[PlacedAnnotation]]]
    takeaways: list[str]
    by_category: list[tuple[str, str, list[PlacedAnnotation]]]
    instruction_notes: list[dict[str, str]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    generated_at: str = ""


def pages_label(p: PlacedAnnotation) -> str:
    pages = sorted({i + 1 for i in p.pages})
    if len(pages) == 1:
        return f"p. {pages[0]}"
    return f"pp. {pages[0]}-{pages[-1]}"


def _short(text: str, limit: int = 320) -> str:
    t = " ".join(text.split())
    return t if len(t) <= limit else t[: limit - 3].rsplit(" ", 1)[0] + "..."


def build_summary(data: dict[str, Any] | None, placed: list[PlacedAnnotation], document_name: str,
                  instruction_notes: list[dict[str, str]], warnings: list[str],
                  category_order: list[str]) -> SummaryDoc:
    by_id = {p.id: p for p in placed}

    def cite(ids) -> list[PlacedAnnotation]:
        seen, out = set(), []
        for i in ids or []:
            if i in by_id and i not in seen:
                seen.add(i)
                out.append(by_id[i])
        return out

    data = data or {}
    sections_map: dict[str, list[tuple[str, list[PlacedAnnotation]]]] = {}
    for s in data.get("sections") or []:
        heading = str(s.get("heading", "")).strip()
        points = [(str(pt.get("text", "")).strip(), cite(pt.get("annotation_ids")))
                  for pt in s.get("points") or [] if str(pt.get("text", "")).strip()]
        if heading and points:
            sections_map.setdefault(heading, []).extend(points)
    sections = [(h, sections_map[h]) for h in SECTION_ORDER if h in sections_map]
    sections += [(h, v) for h, v in sections_map.items() if h not in SECTION_ORDER]

    rubric = [(str(r.get("criterion", "")), str(r.get("assessment", "")), cite(r.get("annotation_ids")))
              for r in data.get("rubric_alignment") or [] if r.get("criterion")]

    groups: dict[str, list[PlacedAnnotation]] = {}
    colors_map: dict[str, str] = {}
    for p in sorted(placed, key=lambda p: (min(p.pages), p.id)):
        groups.setdefault(p.category, []).append(p)
        colors_map[p.category] = p.color
    ordered_cats = [c for c in category_order if c in groups] + [c for c in groups if c not in category_order]

    return SummaryDoc(
        document_name=document_name,
        title=str(data.get("title") or f"Summary of {document_name}"),
        purpose=str(data.get("purpose") or ""),
        sections=sections,
        rubric=rubric,
        takeaways=[str(t) for t in data.get("takeaways") or [] if str(t).strip()],
        by_category=[(c, colors_map[c], groups[c]) for c in ordered_cats],
        instruction_notes=instruction_notes,
        warnings=warnings,
        generated_at=datetime.now(UTC).strftime("%Y-%m-%d"),
    )


def to_markdown(s: SummaryDoc) -> str:
    out = [f"# {s.title}", "",
           f"*{s.document_name}. Generated by AI Annotator on {s.generated_at}. Quotations and page numbers are "
           "taken directly from the annotated document.*", ""]
    if s.purpose:
        out += ["## Main argument", "", s.purpose, ""]
    for heading, points in s.sections:
        out += [f"## {heading}", ""]
        for text, refs in points:
            out.append(f"- {text}")
            for r in refs[:3]:
                out.append(f"  > \"{_short(r.text)}\" ({pages_label(r)})")
        out.append("")
    if s.rubric:
        out += ["## Rubric alignment", ""]
        for crit, assess, refs in s.rubric:
            pages = ", ".join(pages_label(r) for r in refs)
            out.append(f"- **{crit}**: {assess}" + (f" ({pages})" if pages else ""))
        out.append("")
    if s.takeaways:
        out += ["## Key takeaways", ""] + [f"- {t}" for t in s.takeaways] + [""]
    if s.by_category:
        out += ["## Annotated passages", ""]
        for cat, _, items in s.by_category:
            out += [f"### {cat}", ""]
            for p in items:
                line = f"- {pages_label(p)}: \"{_short(p.text, 400)}\""
                if p.comment:
                    line += f"  \n  Note: {p.comment}"
                out.append(line)
            out.append("")
    if s.instruction_notes:
        out += ["## Notes about your instructions", ""] + [f"- {n['message']}" for n in s.instruction_notes] + [""]
    if s.warnings:
        out += ["## Processing notes", ""] + [f"- {w}" for w in s.warnings] + [""]
    return "\n".join(out).rstrip() + "\n"


def to_pdf(s: SummaryDoc, path: Path) -> None:
    register_fonts()
    base = ParagraphStyle("b", fontName="DejaVuSerif", fontSize=10.5, leading=15, spaceAfter=4)
    small = ParagraphStyle("s", parent=base, fontSize=8.5, leading=12, textColor=colors.HexColor("#6b6b6b"))
    h1 = ParagraphStyle("h1", fontName="DejaVuSans-Bold", fontSize=17, leading=22, spaceAfter=6)
    h2 = ParagraphStyle("h2", fontName="DejaVuSans-Bold", fontSize=12, leading=16, spaceBefore=12, spaceAfter=4)
    h3 = ParagraphStyle("h3", fontName="DejaVuSans-Bold", fontSize=10.5, leading=14, spaceBefore=8, spaceAfter=2)
    quote = ParagraphStyle("q", parent=base, fontSize=9.5, leading=13.5, leftIndent=14,
                           textColor=colors.HexColor("#3d3d3d"))
    bullet = ParagraphStyle("li", parent=base, leftIndent=12, bulletIndent=0)

    story: list = [Paragraph(escape(s.title), h1),
                   Paragraph(escape(f"{s.document_name}. Generated by AI Annotator on {s.generated_at}. "
                                    "Quotations and page numbers are taken directly from the annotated document."),
                             small), Spacer(1, 6)]
    if s.purpose:
        story += [Paragraph("Main argument", h2), Paragraph(escape(s.purpose), base)]
    for heading, points in s.sections:
        story.append(Paragraph(escape(heading), h2))
        for text, refs in points:
            block = [Paragraph(escape(text), bullet, bulletText="•")]
            for r in refs[:3]:
                block.append(Paragraph(f"“{escape(_short(r.text))}” ({pages_label(r)})", quote))
            story.append(KeepTogether(block))
    if s.rubric:
        story.append(Paragraph("Rubric alignment", h2))
        for crit, assess, refs in s.rubric:
            pages = ", ".join(pages_label(r) for r in refs)
            story.append(Paragraph(f"<b>{escape(crit)}</b>: {escape(assess)}" + (f" ({pages})" if pages else ""),
                                   bullet, bulletText="•"))
    if s.takeaways:
        story.append(Paragraph("Key takeaways", h2))
        story += [Paragraph(escape(t), bullet, bulletText="•") for t in s.takeaways]
    if s.by_category:
        story.append(Paragraph("Annotated passages", h2))
        for cat, color, items in s.by_category:
            swatch = Table([[""]], colWidths=[9], rowHeights=[9])
            swatch.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(color))]))
            story.append(Table([[swatch, Paragraph(escape(cat), h3)]], colWidths=[14, 6.2 * inch],
                               style=TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                                                 ("LEFTPADDING", (0, 0), (-1, -1), 0)])))
            for p in items:
                txt = f"{pages_label(p)}: “{escape(_short(p.text, 400))}”"
                if p.comment:
                    txt += f"<br/><font color='#6b6b6b'>Note: {escape(p.comment)}</font>"
                story.append(Paragraph(txt, bullet, bulletText="•"))
    if s.instruction_notes:
        story.append(Paragraph("Notes about your instructions", h2))
        story += [Paragraph(escape(n["message"]), bullet, bulletText="•") for n in s.instruction_notes]
    if s.warnings:
        story.append(Paragraph("Processing notes", h2))
        story += [Paragraph(escape(w), bullet, bulletText="•") for w in s.warnings]

    doc = SimpleDocTemplate(str(path), pagesize=LETTER, leftMargin=0.9 * inch, rightMargin=0.9 * inch,
                            topMargin=0.8 * inch, bottomMargin=0.8 * inch, title=s.title, author="AI Annotator")
    doc.build(story)
